package config

import (
	"fmt"
	"os"
	"path/filepath"
)

// projectRoot ищет корневую директорию проекта, поднимаясь вверх по дереву каталогов.
// Корнем считается директория, содержащая файл ".env" или "go.mod".
// Если файлы не найдены, возвращает исходную рабочую директорию.
func ProjectRoot() (string, error) {
	// os.Getwd() возвращает текущую рабочую директорию.
	// Это директория, из которой был произведен запуск приложения.
	path, err := os.Getwd()
	if err != nil {
		return "", fmt.Errorf("get working directory: %w", err)
	}

	// Сохраняем исходный путь на случай, если корень проекта так и не будет найден.
	start := path

	// Бесконечный цикл для последовательного обхода родительских директорий вверх по дереву.
	for {
		// Формируем потенциальный путь к файлу .env в текущей анализируемой директории.
		env := filepath.Join(path, ".env")

		// Проверяем существование файла .env.
		// Если ошибка nil, значит файл найден — мы успешно определили корень проекта.
		if _, err := os.Stat(env); err == nil {
			return path, nil
			// Если файл отсутствует, игнорируем ошибку NotExist и продолжаем поиск.
			// Любые другие ошибки (например, проблемы с правами доступа) возвращаем наружу.
		} else if !os.IsNotExist(err) {
			return "", fmt.Errorf("inspect environment file %q: %w", env, err)
		}

		// Дополнительная проверка на наличие go.mod для того случая,
		// когда приложение было запущено не из корневой директории проекта.
		module := filepath.Join(path, "go.mod")
		if _, err := os.Stat(module); err == nil {
			return path, nil
		} else if !os.IsNotExist(err) {
			return "", fmt.Errorf("inspect module file %q: %w", module, err)
		}

		// Поднимаемся на один уровень выше, получая родительскую директорию.
		// filepath.Dir(path) отсекает последний элемент пути.
		parent := filepath.Dir(path)

		// Проверяем, достигли ли мы корня файловой системы (например, "/" в Linux).
		// Если подняться выше невозможно, filepath.Dir(path) вернет тот же самый путь.
		// В таком случае прекращаем поиск и возвращаем исходную директорию запуска приложения.
		if parent == path {
			return start, nil
		}

		// Переходим к следующей итерации цикла, делая родительскую директорию текущей рабочей.
		path = parent
	}
}
